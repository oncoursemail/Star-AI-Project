"""Bounded, session-local conversation threading for STAR's live room.

This index stores classified metadata only. It does not retain transcripts, audio,
viewer messages, provider account IDs, voiceprints, or model-generated summaries.
It does not choose who speaks, moderate content, schedule speech, or authorize tools;
RoomTurnDirector and the existing room host remain authoritative for those decisions.
"""
from __future__ import annotations

from collections import OrderedDict, deque
from dataclasses import dataclass
import math
import re
from threading import RLock


_TOKEN = re.compile(r"^[A-Za-z0-9_.:-]{1,96}$")
_SOURCES = frozenset({"audio", "chat", "game"})
_INTENTS = frozenset(
    {
        "direct_question",
        "direct_request",
        "direct_mention",
        "correction",
        "backchannel",
        "side_conversation",
        "narration",
        "game_event",
        "human_resolution",
        "unknown",
    }
)


def _finite(value: object) -> bool:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return False
    try:
        return math.isfinite(value)
    except OverflowError:
        return False


def _token(value: object) -> bool:
    return isinstance(value, str) and _TOKEN.fullmatch(value) is not None


@dataclass(frozen=True)
class ConversationEvent:
    """A final classified event with opaque, stream-scoped references only."""

    event_id: str
    session_id: str
    speaker_ref: str
    source: str
    intent: str
    sequence: int
    observed_at: float
    addressee_ref: str | None = None
    reply_to_event_id: str | None = None
    topic_ref: str | None = None
    confidence: float = 1.0
    final: bool = True


@dataclass(frozen=True)
class ConversationIndexConfig:
    """Hard bounds for ephemeral conversation context."""

    max_events: int = 128
    max_age_seconds: float = 120.0
    max_future_skew_seconds: float = 0.25
    max_reply_depth: int = 8
    max_topic_events: int = 8
    max_recent_events: int = 12
    max_participants: int = 64
    max_topics: int = 64
    dedupe_capacity: int = 512

    def __post_init__(self) -> None:
        for name, low, high in (
            ("max_events", 1, 4_096),
            ("max_reply_depth", 1, 32),
            ("max_topic_events", 1, 64),
            ("max_recent_events", 1, 64),
            ("max_participants", 1, 1_024),
            ("max_topics", 1, 1_024),
            ("dedupe_capacity", 1, 8_192),
        ):
            value = getattr(self, name)
            if type(value) is not int or not low <= value <= high:
                raise ValueError(f"{name} must be an integer from {low} to {high}")
        if not _finite(self.max_age_seconds) or not 0.1 <= self.max_age_seconds <= 3_600.0:
            raise ValueError("max_age_seconds must be between 0.1 and 3600")
        if not _finite(self.max_future_skew_seconds) or not 0.0 <= self.max_future_skew_seconds <= 5.0:
            raise ValueError("max_future_skew_seconds must be between 0 and 5")


@dataclass(frozen=True)
class ConversationIndexResult:
    accepted: bool
    reason: str
    evicted_events: int = 0


@dataclass(frozen=True)
class ConversationContext:
    """Metadata-only context; payload text is fetched separately from the room store."""

    session_id: str
    event: ConversationEvent
    reply_chain: tuple[ConversationEvent, ...]
    topic_events: tuple[ConversationEvent, ...]
    recent_events: tuple[ConversationEvent, ...]
    missing_reply_parent: bool


@dataclass(frozen=True)
class ConversationIndexStats:
    events: int
    participants: int
    topics: int
    accepted: int
    rejected: int
    expired: int
    evicted: int
    closed: bool


class ConversationContextIndex:
    """Thread final room events for one stream without becoming another director.

    speaker_ref and addressee_ref must be opaque pseudonyms generated by the
    trusted adapter for this source and this stream session. Adapters must not merge
    identities across audio/chat platforms. Create a new index for every stream.
    """

    def __init__(
        self,
        session_id: str,
        config: ConversationIndexConfig | None = None,
    ) -> None:
        if not _token(session_id):
            raise ValueError("session_id must be a bounded opaque token")
        if config is not None and not isinstance(config, ConversationIndexConfig):
            raise TypeError("config must be ConversationIndexConfig or None")
        self.session_id = session_id
        self.config = config or ConversationIndexConfig()
        self._events: OrderedDict[str, ConversationEvent] = OrderedDict()
        self._seen_order: deque[str] = deque()
        self._seen: set[str] = set()
        self._last_sequence = 0
        self._last_observed_at: float | None = None
        self._accepted = 0
        self._rejected = 0
        self._expired = 0
        self._evicted = 0
        self._closed = False
        self._lock = RLock()

    def ingest(self, event: ConversationEvent, *, now: float) -> ConversationIndexResult:
        """Add one final metadata event, rejecting stale, replayed, or cross-session data."""
        with self._lock:
            if self._closed:
                return self._reject("session_closed")
            if not _finite(now):
                return self._reject("invalid_clock")
            if not isinstance(event, ConversationEvent):
                return self._reject("invalid_event_type")
            problem = self._event_problem(event, float(now))
            if problem is not None:
                return self._reject(problem)
            if event.event_id in self._seen:
                return self._reject("duplicate_event")
            if event.sequence <= self._last_sequence:
                return self._reject("out_of_order_sequence")
            if self._last_observed_at is not None and event.observed_at < self._last_observed_at:
                return self._reject("observation_clock_regressed")

            if event.reply_to_event_id is not None:
                parent = self._events.get(event.reply_to_event_id)
                if parent is not None and parent.sequence >= event.sequence:
                    return self._reject("reply_parent_not_earlier")

            self._prune(float(now))
            retained = list(self._events.values())
            if len(retained) >= self.config.max_events:
                retained = retained[1:]
            participants: set[str] = set()
            topics: set[str] = set()
            for item in retained:
                participants.add(item.speaker_ref)
                if item.addressee_ref is not None:
                    participants.add(item.addressee_ref)
                if item.topic_ref is not None:
                    topics.add(item.topic_ref)
            new_participants = {event.speaker_ref}
            if event.addressee_ref is not None:
                new_participants.add(event.addressee_ref)
            if len(participants | new_participants) > self.config.max_participants:
                return self._reject("participant_capacity")
            if event.topic_ref is not None and event.topic_ref not in topics and len(topics) >= self.config.max_topics:
                return self._reject("topic_capacity")

            self._events[event.event_id] = event
            self._seen.add(event.event_id)
            self._seen_order.append(event.event_id)
            while len(self._seen_order) > self.config.dedupe_capacity:
                expired_id = self._seen_order.popleft()
                self._seen.discard(expired_id)

            self._last_sequence = event.sequence
            self._last_observed_at = event.observed_at
            self._accepted += 1

            evicted = 0
            while len(self._events) > self.config.max_events:
                self._events.popitem(last=False)
                self._evicted += 1
                evicted += 1
            return ConversationIndexResult(True, "accepted", evicted)

    def context_for(self, event_id: str, *, now: float) -> ConversationContext | None:
        """Return bounded reply/topic/recent context for a retained event."""
        if not _token(event_id):
            raise ValueError("event_id must be a bounded opaque token")
        if not _finite(now):
            raise ValueError("now must be a finite monotonic timestamp")
        with self._lock:
            if self._closed:
                return None
            self._prune(float(now))
            event = self._events.get(event_id)
            if event is None:
                return None

            reply_chain: list[ConversationEvent] = []
            child = event
            missing_parent = False
            for _ in range(self.config.max_reply_depth):
                parent_id = child.reply_to_event_id
                if parent_id is None:
                    break
                parent = self._events.get(parent_id)
                if parent is None:
                    missing_parent = True
                    break
                if parent.sequence >= child.sequence:
                    missing_parent = True
                    break
                reply_chain.append(parent)
                child = parent
            else:
                if child.reply_to_event_id is not None:
                    missing_parent = True

            prior = [item for item in self._events.values() if item.sequence <= event.sequence]
            if event.topic_ref is None:
                topic_events: list[ConversationEvent] = []
            else:
                topic_events = [item for item in prior if item.topic_ref == event.topic_ref]
            recent_events = prior[-self.config.max_recent_events :]
            return ConversationContext(
                session_id=self.session_id,
                event=event,
                reply_chain=tuple(reply_chain),
                topic_events=tuple(topic_events[-self.config.max_topic_events :]),
                recent_events=tuple(recent_events),
                missing_reply_parent=missing_parent,
            )

    @property
    def stats(self) -> ConversationIndexStats:
        with self._lock:
            return ConversationIndexStats(
                events=len(self._events),
                participants=len(self._participant_refs()),
                topics=len(self._topic_refs()),
                accepted=self._accepted,
                rejected=self._rejected,
                expired=self._expired,
                evicted=self._evicted,
                closed=self._closed,
            )

    def close(self) -> None:
        """Erase all session-local references and permanently close this index."""
        with self._lock:
            self._closed = True
            self._events.clear()
            self._seen.clear()
            self._seen_order.clear()
            self._last_sequence = 0
            self._last_observed_at = None

    def _event_problem(self, event: ConversationEvent, now: float) -> str | None:
        if not _token(event.event_id):
            return "invalid_event_id"
        if not _token(event.session_id):
            return "invalid_event_session"
        if event.session_id != self.session_id:
            return "wrong_session"
        if not _token(event.speaker_ref):
            return "invalid_speaker_ref"
        if event.addressee_ref is not None and not _token(event.addressee_ref):
            return "invalid_addressee_ref"
        if event.reply_to_event_id is not None and not _token(event.reply_to_event_id):
            return "invalid_reply_reference"
        if event.reply_to_event_id == event.event_id:
            return "self_reply"
        if event.topic_ref is not None and not _token(event.topic_ref):
            return "invalid_topic_ref"
        if not isinstance(event.source, str) or event.source not in _SOURCES:
            return "invalid_source"
        if not isinstance(event.intent, str) or event.intent not in _INTENTS:
            return "invalid_intent"
        if type(event.sequence) is not int or event.sequence <= 0:
            return "invalid_sequence"
        if not _finite(event.observed_at):
            return "invalid_observed_at"
        if not _finite(event.confidence) or not 0.0 <= event.confidence <= 1.0:
            return "invalid_confidence"
        if type(event.final) is not bool:
            return "invalid_final_flag"
        if not event.final:
            return "partial_not_retained"
        if event.observed_at > now + self.config.max_future_skew_seconds:
            return "future_event"
        if now - event.observed_at > self.config.max_age_seconds:
            return "stale_event"
        return None

    def _participant_refs(self) -> set[str]:
        participants: set[str] = set()
        for event in self._events.values():
            participants.add(event.speaker_ref)
            if event.addressee_ref is not None:
                participants.add(event.addressee_ref)
        return participants

    def _topic_refs(self) -> set[str]:
        return {event.topic_ref for event in self._events.values() if event.topic_ref is not None}

    def _prune(self, now: float) -> None:
        expired_ids = [
            event_id
            for event_id, event in self._events.items()
            if now - event.observed_at > self.config.max_age_seconds
        ]
        for event_id in expired_ids:
            self._events.pop(event_id, None)
        self._expired += len(expired_ids)

    def _reject(self, reason: str) -> ConversationIndexResult:
        self._rejected += 1
        return ConversationIndexResult(False, reason)
